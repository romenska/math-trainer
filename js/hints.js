export const ZERO_ONE_HINT = "Маяк завжди програє, а сонечко завжди перемагає";

const isZeroOne = (a, b) => a <= 1 || b <= 1;

/** Текстова підказка для a×b або null, якщо її немає. */
export function textHint(a, b) {
  if (isZeroOne(a, b)) return ZERO_ONE_HINT;
  return HINTS[`${Math.min(a, b)}x${Math.max(a, b)}`] || null;
}

/** Адреса картинки-історії для a×b або null (тоді кнопку просто не показуємо). */
export function storyImage(a, b) {
  if (isZeroOne(a, b)) return ASSETS.storyZeroOne;
  if (ASSETS.storyFactors.includes(a)) return ASSETS.story(a, b);
  if (ASSETS.storyFactors.includes(b)) return ASSETS.story(b, a); // 5×2 = 2×5
  return null;
}
